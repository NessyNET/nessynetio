// Generates src/styles/tokens.css and src/lib/palette-data.ts from src/theme/palette.toml (ADR 013).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse } from 'smol-toml';

const ROOT = new URL('../', import.meta.url);
const HEADER = 'Generated by scripts/gen-tokens.mjs from src/theme/palette.toml. Do not edit; run `npm run gen-tokens`.';
const MONO = '"JetBrains Mono Variable", "JetBrains Mono", ui-monospace, "Cascadia Mono", Menlo, monospace';
const ACCENT_CLASSES = ['primary', 'blue', 'orange', 'yellow', 'purple', 'cyan', 'teal', 'pink', 'red'];
const TAGLINE_CLASSES = ['green', 'yellow', 'cyan', 'teal', 'blue', 'purple', 'pink', 'orange'];

const kebab = (key) => key.replaceAll('_', '-');
const declarations = (table) => Object.entries(table).map(([key, hex]) => `  --${kebab(key)}: ${hex};`);

/**
 * @param {{ base: Record<string, string>, accent: Record<string, string>, ansi: { bright: string[] } & Record<string, string[]> }} palette
 * @returns {{ css: string, ts: string }}
 */
export function renderTokens(palette) {
  const { base, accent, ansi } = palette;
  const brightGreen = ansi.bright[2];
  const lines = [
    `/* ${HEADER} */`,
    ':root {',
    ...declarations(base),
    ...declarations(accent),
    '  --text-dim: var(--muted);',
    '  --control-line: var(--comment);',
    `  --primary-hover: ${brightGreen};`,
    '  --s-active: var(--green);',
    '  --s-retired: var(--muted);',
    `  --mono: ${MONO};`,
    '}',
    '',
    ...ACCENT_CLASSES.map((t) => `.accent-${t} { --accent: var(--${t}); }`),
    '',
    ...TAGLINE_CLASSES.map((t) => `.acc-${t} { color: var(--${t}); }`),
  ];
  const data = { base, accent, ansi };
  const ts = `// ${HEADER}\nexport const PALETTE = ${JSON.stringify(data, null, 2)} as const;\n`;
  return { css: `${lines.join('\n')}\n`, ts };
}

function main() {
  const palette = parse(readFileSync(new URL('src/theme/palette.toml', ROOT), 'utf8'));
  const { css, ts } = renderTokens(palette);
  writeFileSync(new URL('src/styles/tokens.css', ROOT), css);
  writeFileSync(new URL('src/lib/palette-data.ts', ROOT), ts);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
