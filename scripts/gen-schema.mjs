// Generates the editor JSON Schemas in content/schema/ from the zod schemas (design 3.2, 3.5.2).
// Node strips the types of the imported .ts module.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import {
  bookmarksFileSchema,
  categoriesFileSchema,
  projectSchema,
  siteFileSchema,
} from '../src/lib/content/schema.ts';

const OUT = new URL('../content/schema/', import.meta.url);
const COMMENT = 'Generated by scripts/gen-schema.mjs from src/lib/content/schema.ts. Do not edit; run `npm run gen-schema`.';

const FILES = {
  'site.json': siteFileSchema,
  'categories.json': categoriesFileSchema,
  'project.json': projectSchema,
  'bookmarks.json': bookmarksFileSchema,
};

/** @returns {Record<string, string>} file name to file text */
export function renderSchemas() {
  return Object.fromEntries(
    Object.entries(FILES).map(([name, schema]) => {
      // draft-07 is the dialect Taplo (Even Better TOML) supports best.
      const json = z.toJSONSchema(schema, { target: 'draft-7' });
      return [name, `${JSON.stringify({ $comment: COMMENT, ...json }, null, 2)}\n`];
    }),
  );
}

function main() {
  mkdirSync(OUT, { recursive: true });
  for (const [name, text] of Object.entries(renderSchemas())) writeFileSync(new URL(name, OUT), text);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
