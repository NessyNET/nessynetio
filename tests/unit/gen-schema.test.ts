import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { renderSchemas } from '../../scripts/gen-schema.mjs';

const rendered: Record<string, string> = renderSchemas();
const read = (name: string): string => readFileSync(new URL(`../../content/schema/${name}`, import.meta.url), 'utf8');

describe('generated JSON Schemas', () => {
  it('emits the four file types', () => {
    expect(Object.keys(rendered).sort()).toEqual(['bookmarks.json', 'categories.json', 'project.json', 'site.json']);
  });

  it.each(Object.keys(rendered))('content/schema/%s is in sync with the zod schemas', (name) => {
    expect(read(name)).toBe(rendered[name]);
  });

  it('is deterministic and carries the generated-file comment', () => {
    expect(renderSchemas()).toEqual(rendered);
    for (const [name, text] of Object.entries(rendered)) {
      expect(JSON.parse(text).$comment, name).toMatch(/Generated by scripts\/gen-schema\.mjs/);
    }
  });

  it('project.json requires the contract keys and keeps unknown keys allowed', () => {
    const project = JSON.parse(rendered['project.json']!);
    expect(project.required).toEqual(
      expect.arrayContaining(['slug', 'name', 'category', 'status', 'summary', 'priority', 'updated', 'description', 'tags', 'get']),
    );
    expect(project.additionalProperties).toEqual({});
    expect(project.properties.status.enum).toEqual(['active', 'retired']);
  });
});
